import { expect, test } from "bun:test";
import { buildSafeSubtitleTracks } from "../src/components/subtitle-track-utils";
import { setTestOrigin } from "./test-origin";

setTestOrigin("https://typetype.test");

test("uses caption variants instead of numeric duplicate language labels", () => {
  const tracks = buildSafeSubtitleTracks([
    {
      url: "https://www.youtube.com/api/timedtext?v=abcdefghijk&lang=en&name=CC1&expire=123&sig=secret",
      mimeType: "text/vtt",
      languageTag: "en",
      displayLanguageName: "English",
      isAutoGenerated: false,
    },
    {
      url: "https://www.youtube.com/api/timedtext?v=abcdefghijk&lang=en&name=DTVCC1&expire=456&sig=secret",
      mimeType: "text/vtt",
      languageTag: "en",
      displayLanguageName: "English",
      isAutoGenerated: false,
    },
  ]);

  expect(tracks.map((track) => track.label)).toEqual(["English (CC1)", "English (DTVCC1)"]);
  expect(tracks.map((track) => new URL(track.src).searchParams.get("name"))).toEqual([
    "CC1",
    "DTVCC1",
  ]);
  for (const track of tracks) {
    const src = new URL(track.src);
    expect(src.origin).toBe("https://typetype.test");
    expect(src.pathname).toBe("/api/subtitles/youtube/abcdefghijk");
    expect(src.searchParams.get("language")).toBe("en");
    expect(src.searchParams.get("variant")).toBe("manual");
    expect(src.searchParams.get("format")).toBe("vtt");
    expect(track.src).not.toContain("secret");
  }
});

test("preserves generated and translated YouTube subtitle selection", () => {
  const [track] = buildSafeSubtitleTracks([
    {
      url: "https://m.youtube.com/api/timedtext?v=abcdefghijk&lang=en&kind=asr&tlang=fr",
      mimeType: "application/ttml+xml",
      languageTag: "fr",
      displayLanguageName: "French",
      isAutoGenerated: false,
    },
  ]);

  const src = new URL(track?.src ?? "");
  expect(src.hostname).toBe("typetype.test");
  expect(src.pathname).toBe("/api/subtitles/youtube/abcdefghijk");
  expect(src.searchParams.get("language")).toBe("en");
  expect(src.searchParams.get("variant")).toBe("auto");
  expect(src.searchParams.get("translation")).toBe("fr");
});

test("marks tracks flagged as generated as automatic", () => {
  const [track] = buildSafeSubtitleTracks([
    {
      url: "https://www.youtube.com/api/timedtext?v=abcdefghijk&lang=de",
      mimeType: "application/ttml+xml",
      languageTag: "de",
      displayLanguageName: "German",
      isAutoGenerated: true,
    },
  ]);

  expect(new URL(track?.src ?? "").searchParams.get("variant")).toBe("auto");
});

test("skips YouTube subtitle URLs without a video or language", () => {
  const tracks = buildSafeSubtitleTracks([
    {
      url: "https://www.youtube.com/api/timedtext?lang=en",
      mimeType: "text/vtt",
      languageTag: "en",
      displayLanguageName: "English",
      isAutoGenerated: false,
    },
  ]);

  expect(tracks).toEqual([]);
});

test("keeps non YouTube subtitle tracks on the generic proxy", () => {
  const [track] = buildSafeSubtitleTracks([
    {
      url: "https://subtitles.example.test/captions.ttml",
      mimeType: "application/ttml+xml",
      languageTag: "en",
      displayLanguageName: "English",
      isAutoGenerated: false,
    },
  ]);

  const src = new URL(track?.src ?? "");
  expect(src.pathname).toBe("/api/proxy");
  expect(src.searchParams.get("url")).toContain("fmt=vtt");
});

function parse(shape: string): Stroke[] {
  return shape.split("|").map((stroke) =>
    stroke.split(",").map((point): [number, number] => {
      const [x = "0", y = "0"] = point.trim().split(" ");
      return [Number(x), Number(y)];
    }),
  );
}


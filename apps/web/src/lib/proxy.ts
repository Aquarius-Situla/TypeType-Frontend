import { API_BASE } from "./env";

const RAW: string = API_BASE;

function absoluteBase(): string {
  if (RAW.startsWith("http")) return RAW;
  if (typeof window === "undefined" || !window.location?.origin) return RAW;
  return window.location.origin + RAW;
}

function mediaHandlePath(url: string): string | null {
  try {
    const parsed = new URL(url, "https://typetype.invalid");
    const match = parsed.pathname.match(/\/media\/(m1_[A-Za-z0-9_-]{24})$/);
    if (!match || parsed.search || parsed.hash) return null;
    return `/media/${match[1]}`;
  } catch {
    return null;
  }
}

export function isMediaHandleUrl(url: string): boolean {
  return mediaHandlePath(url) !== null;
}

function localMediaUrl(url: string): string | null {
  const path = mediaHandlePath(url);
  return path ? `${absoluteBase()}${path}` : null;
}

export function proxyUrl(url: string): string {
  const local = localMediaUrl(url);
  if (local) return local;
  return `${absoluteBase()}/proxy?url=${encodeURIComponent(url)}`;
}

function isRemoteUrl(url: string): boolean {
  return url.startsWith("http://") || url.startsWith("https://");
}

function extractProxyTarget(url: string): string | null {
  try {
    const parsed = new URL(url);
    if (!parsed.pathname.endsWith("/proxy") && !parsed.pathname.endsWith("/api/proxy")) return null;
    return parsed.searchParams.get("url");
  } catch {
    return null;
  }
}

export function proxyDashManifest(url: string): string {
  if (!url) return url;
  const local = localMediaUrl(url);
  if (local) return local;
  return isRemoteUrl(url) ? proxyUrl(url) : url;
}

const BILIBILI_IMAGE_SIZES = {
  card: "@672w_378h_1c.webp",
  poster: "@1280w_720h_1c.webp",
  avatar: "@240w_240h_1c.webp",
};

type ImageSize = "card" | "poster";

function sizeBilibiliImage(parsed: URL, size: ImageSize): void {
  if (parsed.pathname.includes("@")) return;
  if (parsed.pathname.startsWith("/bfs/archive/")) parsed.pathname += BILIBILI_IMAGE_SIZES[size];
  else if (parsed.pathname.startsWith("/bfs/face/")) parsed.pathname += BILIBILI_IMAGE_SIZES.avatar;
}

function normalizeBilibiliImageUrl(url: string, size: ImageSize): string {
  let normalized = url.trim();
  if (normalized.startsWith("//")) {
    normalized = `https:${normalized}`;
  }
  normalized = normalized.replace(/^http:\/\//, "https://");
  try {
    const parsed = new URL(normalized);
    if (parsed.hostname.endsWith("biliimg.com")) parsed.hostname = "i0.hdslb.com";
    if (parsed.hostname.endsWith("hdslb.com")) {
      sizeBilibiliImage(parsed, size);
      return parsed.toString();
    }
  } catch {
    // ignore
  }
  return normalized;
}

function needsProxy(url: string): boolean {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "http:" && parsed.protocol !== "https:") return false;
    const host = parsed.hostname;
    return (
      host.endsWith("ggpht.com") ||
      host.endsWith("googleusercontent.com") ||
      host.endsWith("hdslb.com") ||
      host.endsWith("biliimg.com") ||
      host.endsWith("ytimg.com")
    );
  } catch {
    return false;
  }
}

export function proxyImage(url: string, size: ImageSize = "card"): string {
  if (!url) return url;
  const raw = extractProxyTarget(url) ?? url;
  const normalized = normalizeBilibiliImageUrl(
    raw.startsWith("httpss://") ? `https://${raw.slice(9)}` : raw,
    size,
  );
  if (!needsProxy(normalized)) return normalized;
  return proxyUrl(normalized);
}

export function toSubtitleVttUrl(url: string, isAutoGenerated = false): string {
  const parsed = new URL(url);
  const youtubeTimedText =
    (parsed.hostname === "youtube.com" || parsed.hostname.endsWith(".youtube.com")) &&
    parsed.pathname === "/api/timedtext";
  if (youtubeTimedText) return youtubeSubtitleUrl(parsed, isAutoGenerated);
  parsed.searchParams.set("fmt", "vtt");
  return proxyUrl(parsed.toString());
}

function youtubeSubtitleUrl(timedText: URL, isAutoGenerated: boolean): string {
  const params = timedText.searchParams;
  const videoId = params.get("v");
  const language = params.get("lang");
  if (!videoId || !language) throw new Error("Incomplete YouTube subtitle URL");
  const automatic =
    isAutoGenerated ||
    params.get("kind") === "asr" ||
    params.get("vssId")?.startsWith("a.") === true;
  const query = new URLSearchParams({
    language,
    variant: automatic ? "auto" : "manual",
    format: "vtt",
  });
  const name = params.get("name");
  if (name) query.set("name", name);
  const translation = params.get("tlang");
  if (translation) query.set("translation", translation);
  return `${absoluteBase()}/subtitles/youtube/${encodeURIComponent(videoId)}?${query}`;
}
